namespace Shared.Contracts;

/// <summary>
/// Единственное место, где живёт правило таймаута инструмента, общее для UI, хоста Visual Studio
/// и хоста VS Code.
/// <para>
/// Длительность команды ограничивают ТРИ разных часов, и раньше каждые показывали своё время:
/// </para>
/// <list type="number">
/// <item>клиент — <c>VsBridge.SendRequestAsync</c> ждёт ответа хоста;</item>
/// <item>хост — <c>ToolExecutor</c> передаёт лимит в <c>ProcessExecutor</c>, который убивает
/// дерево процессов;</item>
/// <item>процесс — сам <c>spawnSync</c>/<c>Task.Delay</c> внутри исполнителя.</item>
/// </list>
/// <para>
/// Настройка <c>CommonOptions.ToolTimeoutMs</c> управляла только ПЕРВЫМИ часами, а лимит процесса
/// был константой 120 000 мс в двух файлах. Рассинхрон ломал оба направления: при настройке
/// меньше 120 с клиент бросал ожидание раньше, чем хост убивал команду (результат убитой команды
/// уже никто не прочитает, а модель получала ложное «Transport failure»), при настройке больше
/// 120 с хост убивал команду, хотя пользователь разрешил больше.
/// </para>
/// <para>
/// Инвариант, который делает рассинхрон невозможным: лимит берётся из настройки и едет в запросе,
/// а клиент ждёт СТРОГО дольше, чем убивает хост (<see cref="ClientWait"/>). Тогда первым всегда
/// срабатывает хост, и его честный ответ «Command timed out after N ms» доезжает до модели.
/// </para>
/// </summary>
public static class ToolTimeout
{
    /// <summary>
    /// Лимит внешней команды (bash/shell-скрипт) по умолчанию, мс. Совпадает с дефолтом
    /// настройки <c>CommonOptions.ToolTimeoutMs</c>, поэтому «настройку не трогали» и
    /// «историческое поведение» — одно и то же число.
    /// </summary>
    public const int DefaultCommandMs = 120_000;

    /// <summary>
    /// Лимит ОДНОГО вызова MCP-инструмента по умолчанию, мс. Другой дефолт, чем у bash, осознанно:
    /// MCP-инструменты — это удалённые сервисы и тяжёлые операции (индексация, поиск), две минуты
    /// там режут нормальную работу. Правило канала при этом ОДНО (<see cref="Resolve"/>),
    /// различаются только значения по умолчанию.
    /// <para>
    /// ВАЖНО: это ФОЛБЭК, а не действующий лимит MCP в продукте: <c>ToolManager</c> кладёт в
    /// аргументы инструмента ту же настройку <c>CommonOptions.ToolTimeoutMs</c>, поэтому реальный
    /// лимит MCP-вызова равен настройке (по умолчанию 120 000 — как у bash). Значение ниже
    /// применяется только когда поле отсутствует или неположительно (хост зовут напрямую).
    /// </para>
    /// </summary>
    public const int DefaultMcpCallMs = 600_000;

    /// <summary>
    /// Лимит прямого запуска исполняемого файла (<c>ProcessExecutor.ExecuteAsync</c>) по умолчанию, мс.
    /// </summary>
    public const int DefaultExecuteMs = 30_000;

    /// <summary>
    /// Насколько дольше хостового лимита ждёт клиент. Запас нужен, чтобы ответ хоста о таймауте
    /// успел дойти: убийство дерева процессов, чтение остатков stdout/stderr и обратный путь по
    /// WebView2 занимают время, и обрыв клиента на той же миллисекунде превращает осмысленный
    /// отказ хоста в ложную транспортную аварию.
    /// </summary>
    public const int ClientGraceMs = 30_000;

    /// <summary>
    /// Насколько дольше самого MCP-вызова ждёт его хостовая цепочка: <c>McpHostSupervisor</c>
    /// отправляет запрос в отдельный процесс и сам ограничен этим запасом. Без учёта этого звена
    /// клиент и хост снова оказывались бы на одной миллисекунде — только теперь в MCP-канале.
    /// </summary>
    public const int McpHostGraceMs = 30_000;

    /// <summary>
    /// Правило канала: отсутствующее (или неположительное) значение означает «взять дефолт этого
    /// инструмента», а не «без лимита». Ноль здесь НЕ значит «без ограничения» — иначе
    /// <c>Task.Delay(0)</c> убивал бы команду мгновенно, а <c>timeout: 0</c> в Node отключал бы
    /// лимит; одно и то же поле получало бы противоположные смыслы на двух хостах.
    /// </summary>
    public static int Resolve(int requestedMs, int fallbackMs)
        => requestedMs > 0 ? requestedMs : fallbackMs;

    /// <summary>
    /// Сколько ждать ответа хоста: весь путь запроса плюс <see cref="ClientGraceMs"/>. Путь — это
    /// сам лимит плюс внутренние запасы хоста (<paramref name="hostExtraMs"/>), потому что клиент
    /// обязан ждать дольше ВСЕЙ цепочки, а не только её последнего звена: MCP-запрос идёт
    /// UI → ToolExecutor → отдельный процесс McpHost → MCP-сервер, и каждое звено добавляет время.
    /// <para>
    /// Слагаемые складываются в <see cref="long"/> и насыщаются на <see cref="int.MaxValue"/>: в
    /// <c>int</c> сумма переполняется в ОТРИЦАТЕЛЬНОЕ время, а <c>CancellationTokenSource</c> с
    /// отрицательной задержкой (кроме -1) бросает <c>ArgumentOutOfRangeException</c> — то есть
    /// кривое значение настройки в localStorage превращалось бы в исключение на каждом вызове
    /// инструмента вместо «ждём максимально долго». Слайдер в UI такого не даёт, но настройка
    /// приходит из хранилища, а не из разметки.
    /// </para>
    /// </summary>
    public static TimeSpan ClientWait(int settingMs, int hostExtraMs = 0, int fallbackMs = DefaultCommandMs)
        => TimeSpan.FromMilliseconds(
            Math.Min((long)int.MaxValue, (long)Resolve(settingMs, fallbackMs) + hostExtraMs + ClientGraceMs));
}
